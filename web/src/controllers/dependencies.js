export function createFeatureContext(context, feature) {
  const contract = contracts[feature];
  if (!contract) throw new Error(`Unknown controller context: ${feature}`);
  const state = {};
  for (const field of contract.stateFields) Object.defineProperty(state, field, {
    enumerable: true, get: () => context.state[field], set: value => { context.state[field] = value; },
  });
  Object.preventExtensions(state);
  const dependencies = {};
  for (const name of contract.members) Object.defineProperty(dependencies, name, {
    enumerable: true, get: () => context[name], set: value => { context[name] = value; },
  });
  Object.defineProperty(dependencies, 'state', { enumerable: true, get: () => state });
  return Object.preventExtensions(dependencies);
}
